expect "--pre-commit does not check the evidence paths (the files are not committed yet)" 0 'ok .*covers'
cp "$mkf" "$work/r/tests/results/"
g add tests/results
g commit -q -m "result whose evidence is missing"
ci --verify-result "$work/r/tests/results/$evname"
expect "a result whose evidence is not committed with it is rejected" 1 '2 evidence path(s) named by the result are not committed.*evidence/ev1/a.log, evidence/ev1/b.log'
mkdir -p "$work/r/tests/results/evidence/ev1"
printf 'log\n' >"$work/r/tests/results/evidence/ev1/a.log"
mk "$pc" "$(g rev-parse HEAD)" false host -evdir pass pass
python3 -B - "$mkf" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
d["cases"][0]["evidence"] = ["evidence/ev1"]
json.dump(d, open(sys.argv[1], "w"))
PY
evdir=$(basename "$mkf")
cp "$mkf" "$work/r/tests/results/"
g add "tests/results/$evdir"
g commit -q -m "result whose evidence is a directory"
ci --verify-result "$work/r/tests/results/$evdir"
expect "a directory named as evidence is rejected (only committed files count)" 1 '1 evidence path(s) named by the result are not committed.*evidence/ev1'
g add tests/results
g commit -q -m "evidence a"
ci --verify-result "$work/r/tests/results/$evname"
expect "... one missing path of two is still rejected" 1 '1 evidence path(s) named by the result are not committed.*evidence/ev1/b.log'
printf 'log\n' >"$work/r/tests/results/evidence/ev1/b.log"
g add tests/results
g commit -q -m "evidence b"
ci --verify-result "$work/r/tests/results/$evname"
expect "a result with all its evidence committed is accepted" 0 'ok .*covers'

# ---- exact commit rule: renames, allowed and disallowed changes -------------------------------------
mk "$pc" "$base" false host -anc pass
ci --verify-result "$mkf" --pre-commit
expect "accepts an ancestor when only results, audits, checkpoint files and the README table changed" 0 'ok .*covers'
ci --verify-result "$mkf" --pre-commit --commit "$base"
expect "--commit SHA verifies that commit (git_sha equal)" 0 'ok '

g checkout -q -b ren
g mv src/a.c tests/results/moved.c
g commit -q -m "rename out of src"
ci --verify-result "$mkf" --pre-commit --commit ren
expect "rejects a rename of a source file into tests/results/" 1 'outside the allowed set: src/a.c'
g checkout -q "$br"
g branch -q -D ren

printf 'b\n' >"$work/r/CHECKPOINT.md"
printf 'n\n' >"$work/r/NEXT_ACTIONS.md"
printf 'audit\n' >"$work/r/docs/audits/M5.md"
g add -A
g commit -q -m "checkpoint and audit"
ci --verify-result "$mkf" --pre-commit
expect "CHECKPOINT.md, NEXT_ACTIONS.md and docs/audits/ may change" 0 'ok '

mkdir -p "$work/r/tests/fuzz/findings" "$work/r/tests/fuzz/campaign" "$work/r/docs"
printf 'row1\nrow2\n' >"$work/r/tests/fuzz/campaign/known.tsv"
printf 'x\n' >"$work/r/docs/SECURITY_FINDINGS.md"
printf 'x\n' >"$work/r/docs/UPSTREAM_REPORTS.md"
printf 'x\n' >"$work/r/tests/fuzz/findings/x.bin"
g add -A
g commit -q -m "classification"
ci --verify-result "$mkf" --pre-commit
expect "a new known.tsv, SECURITY_FINDINGS.md, UPSTREAM_REPORTS.md and a new tests/fuzz/findings/ file may change" 0 'ok '

# the result is now "tested" at this commit: record it as the base for the add-only and append-only rules
mk "$pc" "$(g rev-parse HEAD)" false host -cls pass
printf 'row1\nrow2\nrow3\n' >"$work/r/tests/fuzz/campaign/known.tsv"
printf 'y\n' >"$work/r/tests/fuzz/findings/new.bin"
g add -A
g commit -q -m "append row, add finding"
ci --verify-result "$mkf" --pre-commit
expect "appending to known.tsv and adding a findings file is accepted" 0 'ok '

printf 'row1\nROW2\nrow3\n' >"$work/r/tests/fuzz/campaign/known.tsv"
g add -A
g commit -q -m "edit a middle row"
ci --verify-result "$mkf" --pre-commit
expect "rejects a known.tsv whose old content is not a prefix (middle row edited)" 1 'outside the allowed set: tests/fuzz/campaign/known.tsv'
printf 'new\nrow1\nrow2\nrow3\n' >"$work/r/tests/fuzz/campaign/known.tsv"
g add -A
g commit -q -m "insert a row above"
ci --verify-result "$mkf" --pre-commit
expect "rejects a row inserted above the old rows of known.tsv" 1 'outside the allowed set: tests/fuzz/campaign/known.tsv'
printf 'row1\nrow2\nrow3\n' >"$work/r/tests/fuzz/campaign/known.tsv"
g add -A
g commit -q -m "known.tsv back"

printf 'changed\n' >"$work/r/tests/fuzz/findings/x.bin"
g add -A
g commit -q -m "modify a finding"
ci --verify-result "$mkf" --pre-commit
expect "rejects a modified existing tests/fuzz/findings/ file" 1 'outside the allowed set: tests/fuzz/findings/x.bin'
g rm -q -f tests/fuzz/findings/x.bin
g commit -q -m "delete a finding"
ci --verify-result "$mkf" --pre-commit
expect "rejects a deleted existing tests/fuzz/findings/ file" 1 'outside the allowed set: tests/fuzz/findings/x.bin'
printf 'x\n' >"$work/r/tests/fuzz/findings/x.bin"
g add -A
g commit -q -m "finding restored"

printf 'y\n' >"$work/r/tests/fuzz/campaign/triage.py"
g add -A
g commit -q -m "triage code"
ci --verify-result "$mkf" --pre-commit
expect "rejects a change to tests/fuzz/campaign/triage.py (code, not classification)" 1 'outside the allowed set: tests/fuzz/campaign/triage.py'
g rm -q -f tests/fuzz/campaign/triage.py
g commit -q -m "drop triage code"
printf 'y\n' >"$work/r/tests/fuzz/campaign/known.tsv.bak"
g add -A
g commit -q -m "lookalike"
ci --verify-result "$mkf" --pre-commit
expect "rejects a lookalike of known.tsv" 1 'outside the allowed set: tests/fuzz/campaign/known.tsv.bak'
g rm -q -f tests/fuzz/campaign/known.tsv.bak
g commit -q -m "drop lookalike"

sed 's/^old$/hand edited/;/^<!-- status-table:begin/{n;s/.*/hand edited/;}' "$work/r/README.md" >"$work/r/README.t" && mv "$work/r/README.t" "$work/r/README.md"
g add -A
g commit -q -m "table edited by hand"
ci --verify-result "$mkf" --pre-commit
expect "rejects a README table that is not what report.py renders from the results" 1 'status table is not what report.py renders'
python3 -B "$work/r/tests/harness/report.py" --repo "$work/r" readme >/dev/null
sed 's/^intro$/intro changed/' "$work/r/README.md" >"$work/r/README.t" && mv "$work/r/README.t" "$work/r/README.md"
g add -A
g commit -q -m "README text edit"
ci --verify-result "$mkf" --pre-commit
expect "rejects a README change outside the status table" 1 'outside the allowed set: README.md'

printf 'y\n' >"$work/r/src/a.c"
g add -A
g commit -q -m "source change"
ci --verify-result "$mkf" --pre-commit
expect "rejects an ancestor when source changed since the tested commit" 1 'outside the allowed set: .*src/a.c'
head=$(g rev-parse HEAD)
mk "$pc" "$head" false host "" pass
ci --verify-result "$mkf" --pre-commit
expect "accepts a result for HEAD itself" 0 'ok '
ci --verify-result "$mkf" --pre-commit --commit "$base"
expect "rejects a git_sha that is neither the commit nor its ancestor (--commit older)" 1 'neither the commit under verification'

# ---- --require-env and the stage plan ----------------------------------------------------------------
# a stub test-all whose plans are known
cat >"$work/stub.sh" <<'STUB'
#!/bin/sh
# stub of scripts/test-all.sh: --env E --out FILE [--dry-run ...]
# STUB_FAIL=E: a stage of E fails (exit 1); STUB_NOFILE=E: exit 0 without a result file;
# STUB_MISSING=E: the result of E lacks its last plan stage; STUB_MODE=TEXT: the run mode recorded (default
# full); STUB_NOMODE=E: the result of E has no mode record; STUB_SKIP=CASE-ID: that case is a skip with the
# note STUB_SKIPNOTE (default: the note of the real plan for the by-design skips); STUB_EXTRA="ID:status ...":
# more cases in the result (stress and harness cases merged into a real result). The plan of env host is the
# REAL one (STUB_REAL_TEST_ALL --env host --dry-run), notes of the by-design skips included.
env=; out=; dry=0
while [ $# -gt 0 ]; do
	case $1 in
	--env) env=$2; shift ;;
	--out) out=$2; shift ;;
	--dry-run) dry=1 ;;
	esac
	shift
done
plan() {
	case $1 in
	host) sh "$STUB_REAL_TEST_ALL" --env host --dry-run | sed -n 's/^ *[0-9][0-9]*  \([^ ]*\) .*/\1/p' ;;
	A) echo "preflight selftest harness" ;;
	B) echo "preflight build-release integration" ;;
	esac
}
if [ $dry = 1 ]; then
	echo "test-all plan: env=$env"
	n=0
	if [ "$env" = host ]; then sh "$STUB_REAL_TEST_ALL" --env host --dry-run; exit 0; fi
	for s in $(plan "$env"); do n=$((n + 1)); printf '%2d  %-22s something\n' "$n" "$s"; done
	echo "dry run: nothing was run"
	exit 0
fi
echo "$env" >>"$STUB_LOG"
[ "${STUB_NOFILE:-}" != "$env" ] || exit 0
python3 -B - "$out" "$env" "$STUB_REPO" "$(plan "$env")" <<'PY'
import json, os, subprocess, sys
out, env, repo, plan = sys.argv[1:5]
sys.path.insert(0, os.path.join(repo, "tests", "harness"))
import report
sha, dirty = report.git_info(repo)
names = plan.split()
if os.environ.get("STUB_MISSING") == env:
    names = names[:-1]
st = "fail" if os.environ.get("STUB_FAIL") == env else "pass"
cases = [{"id": report.stage_case_id(env, n), "status": st, "duration_s": 1, "evidence": [], "note": None} for n in names]
import re
by_design = {}
if env == "host":  # what the real plan declares as skipped, with its notes
    real = subprocess.run(["sh", os.environ["STUB_REAL_TEST_ALL"], "--env", "host", "--dry-run"], stdout=subprocess.PIPE).stdout.decode()
    for n, note in re.findall(r"^\s*\d+ {2}(\S+) .*? {2}\[([^\]]+)\]\s*$", real, re.M):
        by_design[report.stage_case_id(env, n)] = note
for x in os.environ.get("STUB_EXTRA", "").split():
    i, st_ = x.rsplit(":", 1)
    cases.append({"id": i, "status": st_, "duration_s": 1, "evidence": [], "note": "why" if st_ == "skip" else None})
skip = os.environ.get("STUB_SKIP", "")
for c in cases:
    if c["id"] in by_design and c["status"] == "pass":
        c["status"], c["note"] = "skip", by_design[c["id"]]
    if c["id"] == skip:
        c["status"], c["note"] = "skip", os.environ.get("STUB_SKIPNOTE") or by_design.get(skip, "some note")
if os.environ.get("STUB_NOMODE") != env:
    cases.append({"id": report.stage_case_id(env, "mode"), "status": "pass", "duration_s": 0, "evidence": [],
                  "note": os.environ.get("STUB_MODE", "full")})
doc = {"schema": "ntfsmac-test-result/1", "git_sha": sha, "dirty_tree": dirty, "env": env, "host_os": "macOS",
       "guest_os": None, "macfuse_version": None, "ntfs3g_version": None, "started": "2026-11-20T10:00:00Z",
       "finished": "2026-11-20T10:00:01Z", "cases": cases}
json.dump(doc, open(out, "w"))
PY
[ "${STUB_RC3:-}" != "$env" ] || exit 3 # every stage passed, the result is marked dirty (test-all.sh exit 3)
[ "${STUB_FAIL:-}" != "$env" ]
STUB
chmod +x "$work/stub.sh"
export STUB_REAL_TEST_ALL="$repo/scripts/test-all.sh"
export STUB_REPO="$work/r" STUB_LOG="$work/stub.log" CI_LOCAL_TEST_ALL="$work/stub.sh"

# results for HEAD in the stub's format, written by the stub itself
stubres="$work/stubres"
mkdir -p "$stubres"
n7=$(printf '%.7s' "$head")
for e in host A B; do
	"$work/stub.sh" --env "$e" --out "$stubres/2026-11-20-$n7-$e.json"
done
# the -ci files (stages ci-local runs itself), as full mode writes them
mk "$stubres" "$head" false host -ci STAGE-HOST-BOOTSTRAP:pass STAGE-HOST-TSAN:pass STAGE-HOST-STATIC-ANALYSIS:pass
mk "$stubres" "$head" false A -ci STAGE-A-LINUX-BUILD-TEST:pass STAGE-A-FUZZ-SHORT:pass
