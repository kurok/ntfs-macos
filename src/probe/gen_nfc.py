"""Generate src/probe/nfc_data.h from the Unicode data of Python's unicodedata.

Usage: python3 -I src/probe/gen_nfc.py > src/probe/nfc_data.h

The probe (check 5a, ADR-023) tests whether a stored file name equals its NFC
form. It does not link CoreFoundation (the sandboxed probe has no Mach
services, and Environment A has no CoreFoundation), so it carries the three
tables UAX #15 needs:
  ccc    canonical combining class of every code point with a non-zero class;
  decomp full canonical decomposition of every code point that has one (Hangul
         syllables are left to the algorithm in nfc.c);
  comp   primary composites: pairs (first, second) that NFC composes;
  assigned  ranges of code points that have a category other than Cn in this Unicode
         version (private-use code points are Co, so they count as assigned; surrogates
         are left out: nfc.c treats a lone surrogate as a neutral unit). A name with a code
         point outside these ranges is not trusted to be NFC: the tables cannot know how a
         newer Unicode version normalises it, so the probe counts it as not NFC (fail
         closed, ADR-023).
A pair is a primary composite when NFC of the two code points is one code
point; that test also excludes the composition exclusions, the singletons and
the non-starter decompositions, so no exclusion list is needed here.
Regenerate after changing Python (the Unicode version is printed in the
header) and run tests/unit/probe/test_nfc.py.
"""
import sys
import unicodedata

MAX_CP = 0x110000
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def main():
    ccc = []
    decomp = []
    comp = []
    for cp in range(MAX_CP):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        c = unicodedata.combining(ch)
        if c:
            ccc.append((cp, c))
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        nfd = unicodedata.normalize("NFD", ch)
        if nfd != ch:
            decomp.append((cp, [ord(x) for x in nfd]))
        raw = unicodedata.decomposition(ch)
        if raw and not raw.startswith("<"):
            parts = [int(x, 16) for x in raw.split()]
            if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch:
                comp.append((parts[0], parts[1], cp))
    comp.sort()
    assigned = []
    for cp in range(MAX_CP):
        if 0xD800 <= cp <= 0xDFFF or unicodedata.category(chr(cp)) == "Cn":
            continue
        if assigned and assigned[-1][1] == cp - 1:
            assigned[-1][1] = cp
        else:
            assigned.append([cp, cp])
    assert all(r[1] >= 0x2FF for r in assigned[:1]), "U+0000 to U+02FF must be assigned (nfc.c fast path)"
    pool = []
    rows = []
    for cp, seq in decomp:
        rows.append((cp, len(pool), len(seq)))
        pool.extend(seq)
    assert all(n <= 255 for _, _, n in rows)
    assert max(pool) < MAX_CP and len(pool) < 65536

    out = []
    w = out.append
    w("/* SPDX-License-Identifier: GPL-2.0-or-later */")
    w("/* Generated by src/probe/gen_nfc.py from Unicode %s (Python %s). Do not edit. */"
      % (unicodedata.unidata_version, sys.version.split()[0]))
    w("#define NTFSMAC_NFC_UNICODE_VERSION \"%s\"" % unicodedata.unidata_version)
    w("")
    w("static const struct { uint32_t cp; uint8_t ccc; } nfc_ccc[] = {")
    for i in range(0, len(ccc), 6):
        w("\t" + " ".join("{0x%05X,%d}," % x for x in ccc[i:i + 6]))
    w("};")
    w("")
    w("static const struct { uint32_t cp; uint16_t off; uint8_t len; } nfc_decomp[] = {")
    for i in range(0, len(rows), 4):
        w("\t" + " ".join("{0x%05X,%d,%d}," % x for x in rows[i:i + 4]))
    w("};")
    w("")
    w("static const uint32_t nfc_pool[] = {")
    for i in range(0, len(pool), 8):
        w("\t" + " ".join("0x%05X," % x for x in pool[i:i + 8]))
    w("};")
    w("")
    w("static const struct { uint32_t first; uint32_t second; uint32_t composed; } nfc_comp[] = {")
    for i in range(0, len(comp), 4):
        w("\t" + " ".join("{0x%05X,0x%05X,0x%05X}," % x for x in comp[i:i + 4]))
    w("};")
    w("")
    w("static const struct { uint32_t first; uint32_t last; } nfc_assigned[] = {")
    for i in range(0, len(assigned), 6):
        w("\t" + " ".join("{0x%05X,0x%05X}," % tuple(x) for x in assigned[i:i + 6]))
    w("};")
    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write("ccc %d, decomp %d, pool %d, comp %d, assigned ranges %d\n"
                     % (len(ccc), len(rows), len(pool), len(comp), len(assigned)))


if __name__ == "__main__":
    main()
