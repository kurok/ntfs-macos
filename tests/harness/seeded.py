"""Seeded test data shared by the integrity and compatibility cases: deterministic file sizes and
contents from a seed, a writer that returns the expected (size, SHA-256) per file, and a tree hasher
and comparator. Standard library only; runs under Python 3.9 in the macOS guest."""

import hashlib
import math
import os
import random

KIB = 1024
MIB = 1024 * KIB
DEFAULT_SEED = 20261114
CHUNK = MIB


def plan_sizes(seed, count, max_size=64 * MIB, min_size=KIB):
    rng = random.Random("sizes:%d" % seed)
    lo, hi = math.log(min_size), math.log(max_size)
    sizes = [min_size, max_size][:count]
    while len(sizes) < count:
        sizes.append(max(min_size, min(max_size, int(math.exp(rng.uniform(lo, hi))))))
    return sizes


def file_stream(seed, index, size):
    """Yield the deterministic content of file `index` in chunks."""
    rng = random.Random("data:%d:%d" % (seed, index))
    left = size
    while left > 0:
        n = min(CHUNK, left)
        yield rng.randbytes(n)
        left -= n


def rel_name(index):
    return "d%02d/f%03d.bin" % (index % 10, index)


def write_files(root, seed, sizes):
    """Write the files, return {relpath: (size, sha256)} computed from the generated bytes."""
    expected = {}
    for i, size in enumerate(sizes):
        rel = rel_name(i)
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        h = hashlib.sha256()
        with open(path, "wb") as f:
            for chunk in file_stream(seed, i, size):
                h.update(chunk)
                f.write(chunk)
        expected[rel] = (size, h.hexdigest())
    return expected


# macOS creates these in the volume root of every mount, whatever the file system driver does
# (observed: .fseventsd/fseventsd-uuid, T-M2-03). They are not test data.
MACOS_ROOT_METADATA = (".fseventsd",)


def hash_tree(root):
    out = {}
    for dp, dn, fns in os.walk(root):
        if dp == root:
            dn[:] = [d for d in dn if d not in MACOS_ROOT_METADATA]
        for fn in fns:
            path = os.path.join(dp, fn)
            h = hashlib.sha256()
            size = 0
            with open(path, "rb") as f:
                while True:
                    b = f.read(CHUNK)
                    if not b:
                        break
                    h.update(b)
                    size += len(b)
            out[os.path.relpath(path, root).replace(os.sep, "/")] = (size, h.hexdigest())
    return out


def compare(expected, actual):
    """Return a sorted list of human-readable mismatches; empty means equal."""
    bad = []
    for rel in sorted(expected):
        if rel not in actual:
            bad.append("%s: missing" % rel)
            continue
        es, eh = expected[rel]
        as_, ah = actual[rel]
        if es != as_:
            bad.append("%s: size %d != %d" % (rel, as_, es))
        elif eh != ah:
            bad.append("%s: sha256 %s != expected %s" % (rel, ah, eh))
    for rel in sorted(actual):
        if rel not in expected:
            bad.append("%s: unexpected extra file" % rel)
    return bad


def image_size(total):
    """Image size for `total` bytes of data: headroom for MFT, $LogFile, bitmap and directory indexes."""
    return ((int(total * 1.15) + 160 * MIB) // MIB + 1) * MIB
