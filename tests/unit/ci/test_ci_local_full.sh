#!/bin/sh
# SPDX-License-Identifier: GPL-2.0-or-later
# Tests for scripts/ci-local.sh full mode and --verify-result (T-M5-08). Nothing builds and no VM,
# container or mount is used: the tests run in a throw-away git repository that holds a copy of
# scripts/ci-local.sh and tests/harness, full mode runs against a stub of test-all.sh
# (CI_LOCAL_TEST_ALL) and the stages ci-local runs itself are replaced by stubs (CI_LOCAL_TEST_OWN).
# Not registered with CTest (like test_ci_local.sh).
# Usage: tests/unit/ci/test_ci_local_full.sh   (exit 0 = all pass)
set -eu

here=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
repo=$(CDPATH='' cd -- "$here/../../.." && pwd)
work=$(mktemp -d "${TMPDIR:-/tmp}/ci-local-full-test.XXXXXX")
trap 'rm -rf "$work"' EXIT INT TERM

fails=0
check() { # description, condition-exit-code
	if [ "$2" -eq 0 ]; then echo "PASS  $1"; else echo "FAIL  $1"; fails=$((fails + 1)); fi
}
# expect DESCRIPTION RC PATTERN: the last run exited with RC and its output matches PATTERN
expect() {
	if [ "$rc" -eq "$2" ] && grep -q -- "$3" "$work/out"; then r=0; else r=1; sed 's/^/    | /' "$work/out" | head -25; fi
	check "$1" "$r"
}

g() { git -C "$work/r" -c user.name=t -c user.email=t@example.invalid "$@"; }

# ---- the throw-away repository ---------------------------------------------------------------
mkdir -p "$work/r/scripts" "$work/r/docs/audits" "$work/r/src" "$work/r/tests/results" "$work/pc"
cp "$repo/scripts/ci-local.sh" "$work/r/scripts/"
cp -R "$repo/tests/harness" "$work/r/tests/harness"
rm -rf "$work/r/tests/harness/__pycache__"
printf '#!/bin/sh\nexit 0\n' >"$work/r/scripts/bootstrap.sh"
chmod +x "$work/r/scripts/bootstrap.sh"
printf 'x\n' >"$work/r/src/a.c"
printf 'intro\n<!-- status-table:begin (generated by tests/harness/report.py readme; do not edit by hand) -->\nold\n<!-- status-table:end -->\noutro\n' >"$work/r/README.md"
printf 'a\n' >"$work/r/CHECKPOINT.md"
printf '__pycache__/\n' >"$work/r/.gitignore"
git -C "$work/r" init -q
g add -A
g commit -q -m base
base=$(g rev-parse HEAD)
b7=$(printf '%.7s' "$base")
br=$(g rev-parse --abbrev-ref HEAD)
ci() { rc=0; "$work/r/scripts/ci-local.sh" "$@" >"$work/out" 2>&1 || rc=$?; }
pc=$work/pc

# mk DIR SHA7ORFULL DIRTY ENV SUFFIX CASE...: write a result named like the harness names it and set mkf.
# CASE is a status (ids T-CASE-n) or ID:status. ENV "-" leaves env out of the file (the name uses A).
cat >"$work/mk.py" <<'PY'
import json, sys
f, sha, dirty, env = sys.argv[1:5]
cases = []
for i, st in enumerate(sys.argv[5:], 1):
    cid = "T-CASE-%d" % i
    if ":" in st:
        cid, st = st.split(":", 1)
    cases.append({"id": cid, "status": st, "duration_s": 1,
                  "evidence": [], "note": "why" if st == "skip" else None})
doc = {"schema": "ntfsmac-test-result/1", "git_sha": sha, "dirty_tree": dirty == "true", "env": env,
       "host_os": "macOS", "guest_os": None, "macfuse_version": None, "ntfs3g_version": None,
       "started": "2026-11-20T10:00:00Z", "finished": "2026-11-20T10:00:01Z", "cases": cases}
if env == "-":
    del doc["env"]
json.dump(doc, open(f, "w"))
PY
mk() { # DIR SHA DIRTY ENV SUFFIX CASES...
	_d=$1; _sha=$2; _dirty=$3; _env=$4; _sfx=$5; shift 5
	_ne=$_env; [ "$_ne" != "-" ] || _ne=A
	mkf=$_d/2026-11-20-$(printf '%.7s' "$_sha")-$_ne$_sfx.json
	python3 -B "$work/mk.py" "$mkf" "$_sha" "$_dirty" "$_env" "$@"
}

# ---- usage ---------------------------------------------------------------------------------
ci --verify-result
expect "--verify-result without a file exits 2" 2 'needs a file'
ci --only bogus --dry-run
expect "--only with an unknown stage exits 2" 2 "unknown stage"
ci --only , --dry-run
expect "an empty --only selection exits 2" 2 'no stage named'
ci --fuzz-seconds x --dry-run
expect "--fuzz-seconds needs a number" 2 'whole number'
ci --commit HEAD
expect "--commit without --verify-result exits 2" 2 'need --verify-result'
ci --quick --dry-run
expect "--quick --dry-run exits 2" 2 'do not apply to --quick'
ci --quick --only host
expect "--quick --only exits 2" 2 'do not apply to --quick'
ci --quick --results-dir x
expect "--quick --results-dir exits 2" 2 'do not apply to --quick'
ci --quick --allow-dirty
expect "--quick --allow-dirty exits 2" 2 'do not apply to --quick'
ci --quick --fuzz-seconds 5
expect "--quick --fuzz-seconds exits 2" 2 'do not apply to --quick'
ci --quick --commit HEAD
expect "--quick --commit exits 2" 2 'do not apply to --quick'
ci --preset release --dry-run
expect "--preset without --quick exits 2" 2 'need --quick'
ci --verify-result "$work/x.json" --dry-run
expect "--verify-result --dry-run exits 2" 2 'do not apply to --verify-result'
ci --verify-result "$work/x.json" --only host
expect "--verify-result --only exits 2" 2 'do not apply to --verify-result'
ci --verify-result "$work/x.json" --results-dir x
expect "--verify-result --results-dir exits 2" 2 'do not apply to --verify-result'
ci --verify-result "$work/x.json" --quick
expect "--verify-result --quick exits 2" 2 'cannot be combined'
ci --verify-result "$work/nope.json" --pre-commit
expect "unreadable result file exits 2" 2 'cannot read'
mk "$pc" "$base" false host "" pass pass skip
ci --verify-result "$mkf" --pre-commit --commit nosuchrev
expect "unresolvable --commit exits 2" 2 'cannot resolve the commit'

# ---- --verify-result --pre-commit: accepted ----------------------------------------------------
ci --verify-result "$mkf" --pre-commit
expect "a clean result for HEAD is accepted" 0 'ok .*env host.*2 pass, 1 skip'

# ---- one test per rejection --------------------------------------------------------------------
echo '{"schema": "wrong", "env": "A"}' >"$pc/2026-11-20-${b7}-A-badschema.json"
ci --verify-result "$pc/2026-11-20-${b7}-A-badschema.json" --pre-commit
expect "rejects an invalid schema" 1 'REJECTED .*schema invalid'
mk "$pc" 0123456789 false host -short pass
ci --verify-result "$mkf" --pre-commit
expect "rejects a malformed git_sha through the schema check" 1 'schema invalid.*git_sha'
printf 'not json' >"$pc/2026-11-20-${b7}-A-junk.json"
ci --verify-result "$pc/2026-11-20-${b7}-A-junk.json" --pre-commit
expect "rejects a file that is not JSON" 1 'not valid JSON'
mk "$pc" "$base" false host -nan pass
sed 's/"duration_s": 1/"duration_s": NaN/' "$mkf" >"$mkf.t" && mv "$mkf.t" "$mkf"
ci --verify-result "$mkf" --pre-commit
expect "rejects NaN in the JSON" 1 'NaN is not allowed'
mk "$pc" "$base" false host -dup pass
sed 's/"env": "host"/"env": "host", "env": "A"/' "$mkf" >"$mkf.t" && mv "$mkf.t" "$mkf"
ci --verify-result "$mkf" --pre-commit
expect "rejects a duplicate key in the JSON" 1 'duplicate key'
mk "$pc" "$base" false - -noenv pass
ci --verify-result "$mkf" --pre-commit
expect "rejects a result without env" 1 'environment missing'
mk "$pc" "$base" true host -dirty pass
ci --verify-result "$mkf" --pre-commit
expect "rejects dirty_tree true" 1 'dirty_tree is true'
mk "$pc" "$base" false A -failed pass fail
ci --verify-result "$mkf" --pre-commit
expect "rejects a failed case and names it" 1 'failed or errored: T-CASE-2'
mk "$pc" "$base" false A -error pass error
ci --verify-result "$mkf" --pre-commit
expect "rejects an errored case" 1 'failed or errored'
mk "$pc" "$base" false B -allskip skip skip
ci --verify-result "$mkf" --pre-commit
expect "rejects a result in which nothing passed" 1 'no case passed'
mk "$pc" 1111111111111111111111111111111111111111 false host -unknown pass
ci --verify-result "$mkf" --pre-commit
expect "rejects a git_sha that is not in the repository" 1 'not a commit of this repository'
mk "$pc" "$base" false host -foreign pass STAGE-A-SELFTEST:pass
ci --verify-result "$mkf" --pre-commit
expect "rejects a STAGE case of another environment (env/case mismatch)" 1 'another environment'
mk "$pc" "$base" false host -badname pass
mv "$mkf" "$pc/result.json"
ci --verify-result "$pc/result.json" --pre-commit
expect "rejects a file name that is not <date>-<sha7>-<env>" 1 'file name must be'
mk "$pc" "$base" false host -wrongenv pass
mv "$mkf" "$pc/2026-11-20-${b7}-A-wrongenv.json"
ci --verify-result "$pc/2026-11-20-${b7}-A-wrongenv.json" --pre-commit
expect "rejects a file name whose env differs from the content" 1 'does not match git_sha'
mk "$pc" "$base" false host -wrongsha pass
mv "$mkf" "$pc/2026-11-20-abcdef0-host-wrongsha.json"
ci --verify-result "$pc/2026-11-20-abcdef0-host-wrongsha.json" --pre-commit
expect "rejects a file name whose sha differs from git_sha" 1 'does not match git_sha'

# ---- committed mode: path and content ------------------------------------------------------------
mk "$pc" "$base" false host -committed pass pass
ci --verify-result "$mkf"
expect "outside tests/results/ is rejected without --pre-commit" 1 'must lie under tests/results'
cp "$mkf" "$work/r/tests/results/"
name=$(basename "$mkf")
ci --verify-result "$work/r/tests/results/$name"
expect "an uncommitted file under tests/results/ is rejected" 1 'is not committed in'
g add -A
g commit -q -m "results"
python3 -B "$work/r/tests/harness/report.py" --repo "$work/r" readme >/dev/null
g add -A
g commit -q -m "status table"
ci --verify-result "$work/r/tests/results/$name"
expect "a committed result under tests/results/ covers HEAD (ancestor, README table current)" 0 'ok .*covers'
printf ' ' >>"$work/r/tests/results/$name"
ci --verify-result "$work/r/tests/results/$name"
expect "a file that differs from its committed copy is rejected" 1 'differs from the copy committed'
g checkout -q -- tests/results

# ---- exact commit rule: renames, allowed and disallowed changes -------------------------------------
mk "$pc" "$base" false host -anc pass
ci --verify-result "$mkf" --pre-commit
expect "accepts an ancestor when only results, audits, checkpoint files and the README table changed" 0 'ok .*covers'
ci --verify-result "$mkf" --pre-commit --commit "$base"
expect "--commit SHA verifies that commit (git_sha equal)" 0 'ok '

g checkout -q -b ren
g mv src/a.c tests/results/moved.c
g commit -q -m "rename out of src"
ci --verify-result "$mkf" --pre-commit --commit ren
expect "rejects a rename of a source file into tests/results/" 1 'outside the allowed set: src/a.c'
g checkout -q "$br"
g branch -q -D ren

printf 'b\n' >"$work/r/CHECKPOINT.md"
printf 'n\n' >"$work/r/NEXT_ACTIONS.md"
printf 'audit\n' >"$work/r/docs/audits/M5.md"
g add -A
g commit -q -m "checkpoint and audit"
ci --verify-result "$mkf" --pre-commit
expect "CHECKPOINT.md, NEXT_ACTIONS.md and docs/audits/ may change" 0 'ok '

sed 's/^old$/hand edited/;/^<!-- status-table:begin/{n;s/.*/hand edited/;}' "$work/r/README.md" >"$work/r/README.t" && mv "$work/r/README.t" "$work/r/README.md"
g add -A
g commit -q -m "table edited by hand"
ci --verify-result "$mkf" --pre-commit
expect "rejects a README table that is not what report.py renders from the results" 1 'status table is not what report.py renders'
python3 -B "$work/r/tests/harness/report.py" --repo "$work/r" readme >/dev/null
sed 's/^intro$/intro changed/' "$work/r/README.md" >"$work/r/README.t" && mv "$work/r/README.t" "$work/r/README.md"
g add -A
g commit -q -m "README text edit"
ci --verify-result "$mkf" --pre-commit
expect "rejects a README change outside the status table" 1 'outside the allowed set: README.md'

printf 'y\n' >"$work/r/src/a.c"
g add -A
g commit -q -m "source change"
ci --verify-result "$mkf" --pre-commit
expect "rejects an ancestor when source changed since the tested commit" 1 'outside the allowed set: .*src/a.c'
head=$(g rev-parse HEAD)
mk "$pc" "$head" false host "" pass
ci --verify-result "$mkf" --pre-commit
expect "accepts a result for HEAD itself" 0 'ok '
ci --verify-result "$mkf" --pre-commit --commit "$base"
expect "rejects a git_sha that is neither the commit nor its ancestor (--commit older)" 1 'neither the commit under verification'

# ---- --require-env and the stage plan ----------------------------------------------------------------
# a stub test-all whose plans are known
cat >"$work/stub.sh" <<'STUB'
#!/bin/sh
# stub of scripts/test-all.sh: --env E --out FILE [--dry-run ...]
# STUB_FAIL=E: a stage of E fails (exit 1); STUB_NOFILE=E: exit 0 without a result file;
# STUB_MISSING=E: the result of E lacks its last plan stage
env=; out=; dry=0
while [ $# -gt 0 ]; do
	case $1 in
	--env) env=$2; shift ;;
	--out) out=$2; shift ;;
	--dry-run) dry=1 ;;
	esac
	shift
done
plan() {
	case $1 in
	host) echo "build-release unit-release" ;;
	A) echo "preflight selftest harness" ;;
	B) echo "preflight build-release integration" ;;
	esac
}
if [ $dry = 1 ]; then
	echo "test-all plan: env=$env"
	n=0
	for s in $(plan "$env"); do n=$((n + 1)); printf '%2d  %-22s something\n' "$n" "$s"; done
	echo "dry run: nothing was run"
	exit 0
fi
echo "$env" >>"$STUB_LOG"
[ "${STUB_NOFILE:-}" != "$env" ] || exit 0
python3 -B - "$out" "$env" "$STUB_REPO" "$(plan "$env")" <<'PY'
import json, os, subprocess, sys
out, env, repo, plan = sys.argv[1:5]
sys.path.insert(0, os.path.join(repo, "tests", "harness"))
import report
sha, dirty = report.git_info(repo)
names = plan.split()
if os.environ.get("STUB_MISSING") == env:
    names = names[:-1]
st = "fail" if os.environ.get("STUB_FAIL") == env else "pass"
cases = [{"id": report.stage_case_id(env, n), "status": st, "duration_s": 1, "evidence": [], "note": None} for n in names]
doc = {"schema": "ntfsmac-test-result/1", "git_sha": sha, "dirty_tree": dirty, "env": env, "host_os": "macOS",
       "guest_os": None, "macfuse_version": None, "ntfs3g_version": None, "started": "2026-11-20T10:00:00Z",
       "finished": "2026-11-20T10:00:01Z", "cases": cases}
json.dump(doc, open(out, "w"))
PY
[ "${STUB_FAIL:-}" != "$env" ]
STUB
chmod +x "$work/stub.sh"
export STUB_REPO="$work/r" STUB_LOG="$work/stub.log" CI_LOCAL_TEST_ALL="$work/stub.sh"

# results for HEAD in the stub's format, written by the stub itself
stubres="$work/stubres"
mkdir -p "$stubres"
n7=$(printf '%.7s' "$head")
for e in host A B; do
	"$work/stub.sh" --env "$e" --out "$stubres/2026-11-20-$n7-$e.json"
done
ci --verify-result "$stubres/2026-11-20-$n7-host.json" --verify-result "$stubres/2026-11-20-$n7-A.json" \
	--verify-result "$stubres/2026-11-20-$n7-B.json" --pre-commit --require-env host,A,B
expect "host, A and B results with every plan stage satisfy --require-env host,A,B" 0 'verify-result: PASSED'
ci --verify-result "$stubres/2026-11-20-$n7-host.json" --verify-result "$stubres/2026-11-20-$n7-A.json" \
	--pre-commit --require-env host,A,B
expect "--require-env rejects a missing environment" 1 'no accepted result for environment B'
STUB_MISSING=A "$work/stub.sh" --env A --out "$stubres/2026-11-20-$n7-A-missing.json"
ci --verify-result "$stubres/2026-11-20-$n7-A-missing.json" --pre-commit --require-env A
expect "--require-env rejects a result that lacks a stage of the plan" 1 'lacks the stage case.*STAGE-A-HARNESS'
mk "$pc" "$head" false A -nostage pass
ci --verify-result "$mkf" --pre-commit --require-env A
expect "--require-env rejects a result without STAGE cases" 1 'lacks the stage case'
ci --verify-result "$stubres/2026-11-20-$n7-host.json" --verify-result "$pc/2026-11-20-${b7}-A-failed.json" --pre-commit --require-env host
expect "one rejected file fails the whole check" 1 'verify-result: FAILED'

# ---- full mode with the stubs ---------------------------------------------------------------------
full() { : >"$STUB_LOG"; rc=0; CI_LOCAL_TEST_OWN=1 "$work/r/scripts/ci-local.sh" "$@" >"$work/out" 2>&1 || rc=$?; unset STUB_FAIL STUB_NOFILE STUB_MISSING CI_LOCAL_TEST_OWN_FAIL; }
order() { tr '\n' ' ' <"$STUB_LOG"; }
# count_files DIR PATTERN-SUFFIX
nfiles() { set -- "$1"/*"$2"; if [ -e "$1" ]; then echo $#; else echo 0; fi; }

full --dry-run
expect "--dry-run lists every stage of section 9 and exits 0" 0 'static-analysis .*clang-tidy'
if grep -q 'fuzz-short' "$work/out" && grep -q 'linux-build-test' "$work/out" && grep -q ' package ' "$work/out" && grep -q ' tsan ' "$work/out" &&
	grep -q 'preflight .*something' "$work/out" && [ ! -s "$STUB_LOG" ] && grep -q 'require-env host,A,B' "$work/out"; then r=0; else r=1; fi
check "--dry-run shows each stage, each test-all plan, the demanded envs and runs nothing" "$r"

full --results-dir "$work/resall"
expect "full mode, every stage stubbed, passes with --require-env host,A,B derived" 0 'ci-local: PASSED'
if [ "$(order)" = "host A B " ]; then r=0; else r=1; fi
check "test-all runs host, A, B in order" "$r"
r=1
n=$(nfiles "$work/resall" .json)
if [ "$n" -eq 6 ] && [ "$(nfiles "$work/resall" -ci.json)" -eq 3 ]; then r=0; fi
check "six files: host, A, B from test-all and host-ci, A-ci, B-ci from the stages ci-local runs" "$r"
python3 -B - "$work/resall" <<'PY' && r=0 || r=1
import glob, json, sys
ids = {}
for f in glob.glob(sys.argv[1] + "/*-ci.json"):
    d = json.load(open(f))
    ids[d["env"]] = {c["id"]: c for c in d["cases"]}
want = {"host": ["STAGE-HOST-TSAN", "STAGE-HOST-STATIC-ANALYSIS"], "A": ["STAGE-A-LINUX-BUILD-TEST", "STAGE-A-FUZZ-SHORT"],
        "B": ["STAGE-B-PACKAGE"]}
for e, cs in want.items():
    for c in cs:
        assert c in ids[e] and ids[e][c]["status"] == "pass", (e, c)
assert ids["A"]["STAGE-A-FUZZ-SHORT"]["note"] == "stub stage fuzz-short", ids["A"]["STAGE-A-FUZZ-SHORT"]
PY
check "the -ci files hold the right STAGE cases per environment, with the stage note" "$r"

CI_LOCAL_TEST_OWN_FAIL=fuzz-short full --results-dir "$work/resfz"
expect "a failing own stage fails the run and verify-result rejects its -ci file" 1 'REJECTED .*A-ci.json: .*failed or errored: STAGE-A-FUZZ-SHORT'

STUB_NOFILE=A full --results-dir "$work/resnf"
expect "a stage that exits 0 but writes no file fails" 1 'exited 0 but wrote no result file'

STUB_MISSING=B full --results-dir "$work/resmiss"
expect "a missing plan stage in a result fails the final verification" 1 'environment B lacks the stage case.*STAGE-B-INTEGRATION'

STUB_FAIL=host full --only host,B --results-dir "$work/resf"
if [ "$rc" -eq 1 ] && [ "$(order)" = "host B " ] && grep -q 'REJECTED .*failed or errored' "$work/out" && grep -q 'ci-local: FAILED' "$work/out"; then r=0; else r=1; sed 's/^/    | /' "$work/out" | tail -15; fi
check "a failing environment fails the run and B still runs" "$r"

full --only host,B --results-dir "$work/respart"
expect "a partial run demands only the environments it ran (host and B)" 0 'ci-local: PASSED'
ci --verify-result "$work/respart"/*-host.json --pre-commit --require-env A
expect "a partial run's files do not satisfy --require-env A" 1 'no accepted result for environment A'

printf 'dirt\n' >"$work/r/src/a.c"
full --only host --results-dir "$work/resd5"
expect "full mode refuses a dirty tree" 2 'working tree is dirty'
full --only host --results-dir "$work/resd6" --allow-dirty
if [ "$rc" -eq 1 ] && grep -q 'dirty_tree is true' "$work/out" && grep -l '"dirty_tree": true' "$work"/resd6/*.json >/dev/null; then r=0; else r=1; sed 's/^/    | /' "$work/out" | tail -8; fi
check "--allow-dirty runs, marks the results dirty and the final verification rejects them (exit 1)" "$r"
g checkout -q -- src/a.c

if [ "$fails" -eq 0 ]; then echo "ALL PASSED"; exit 0; fi
echo "$fails FAILED"; exit 1
