"""Generate src/common/label_cp_data.h: the non-ASCII part of the label allow-list (ADR-016).

Usage (Environment A, whose Python carries Unicode 15.1.0, the version of the probe's NFC
tables):  python3 -I src/common/gen_label_cp.py > src/common/label_cp_data.h

A code point at or above U+0080 is DENIED (replaced by `_`) if it
  - has general category Cn (unassigned in 15.1.0, noncharacters included: fail closed),
    Cc, Cf, Cs, Co, Zs, Zl or Zp;
  - is a Default_Ignorable_Code_Point (DerivedCoreProperties.txt of 15.1.0, listed below;
    Python has no such property);
  - is a slash look-alike (U+2044 U+2215 U+29F8 U+FF0F) or the colon look-alike U+FF1A.
The Hangul fillers U+115F U+1160 U+3164 U+FFA0 are Default_Ignorable_Code_Points (Lo) and are
covered by that list. A combining mark (general category Mn, Mc, Me) is allowed inside a
label but not at its start; those ranges are the second table.
The header prints the Unicode version it was made from; the generator refuses to run on another.
"""
import sys
import unicodedata

VERSION = "15.1.0"

# Default_Ignorable_Code_Point, Unicode 15.1.0 (DerivedCoreProperties.txt).
DEFAULT_IGNORABLE = [
    (0x00AD, 0x00AD), (0x034F, 0x034F), (0x061C, 0x061C), (0x115F, 0x1160),
    (0x17B4, 0x17B5), (0x180B, 0x180F), (0x200B, 0x200F), (0x202A, 0x202E),
    (0x2060, 0x206F), (0x3164, 0x3164), (0xFE00, 0xFE0F), (0xFEFF, 0xFEFF),
    (0xFFA0, 0xFFA0), (0xFFF0, 0xFFF8), (0x1BCA0, 0x1BCA3), (0x1D173, 0x1D17A),
    (0xE0000, 0xE0FFF),
]
LOOKALIKES = (0x2044, 0x2215, 0x29F8, 0xFF0F, 0xFF1A)
DENIED_CATEGORIES = {"Cn", "Cc", "Cf", "Cs", "Co", "Zs", "Zl", "Zp"}
MARK_CATEGORIES = {"Mn", "Mc", "Me"}


def ranges(pred):
    out, start = [], None
    for cp in range(0x80, 0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rs):
    lines = ["static const uint32_t %s[][2] = {" % name]
    row = []
    for a, b in rs:
        row.append("{ 0x%04X, 0x%04X }," % (a, b))
        if len(row) == 4:
            lines.append("\t" + " ".join(row))
            row = []
    if row:
        lines.append("\t" + " ".join(row))
    lines.append("};")
    return "\n".join(lines)


def main():
    if unicodedata.unidata_version != VERSION:
        sys.exit("gen_label_cp.py: Unicode %s needed, this Python has %s (run it in Environment A)"
                 % (VERSION, unicodedata.unidata_version))
    di = set()
    for a, b in DEFAULT_IGNORABLE:
        di.update(range(a, b + 1))

    def denied(cp):
        if 0xD800 <= cp <= 0xDFFF:
            return True
        return (unicodedata.category(chr(cp)) in DENIED_CATEGORIES or cp in di or cp in LOOKALIKES)

    def mark(cp):
        return unicodedata.category(chr(cp)) in MARK_CATEGORIES and not denied(cp)

    d, m = ranges(denied), ranges(mark)
    print("/* SPDX-License-Identifier: GPL-2.0-or-later */")
    print("/* Generated by src/common/gen_label_cp.py from Unicode %s. Do not edit. */" % VERSION)
    print("#ifndef NTFSMAC_LABEL_CP_DATA_H")
    print("#define NTFSMAC_LABEL_CP_DATA_H")
    print()
    print("#include <stdint.h>")
    print()
    print('#define NTFSMAC_LABEL_CP_UNICODE_VERSION "%s"' % VERSION)
    print()
    print("/* Code points at or above U+0080 that the label allow-list replaces (ADR-016). */")
    print(table("label_cp_denied", d))
    print()
    print("/* Combining marks (Mn, Mc, Me) that are allowed, but not at the start of a part. */")
    print(table("label_cp_marks", m))
    print()
    print("#endif /* NTFSMAC_LABEL_CP_DATA_H */")


if __name__ == "__main__":
    main()
