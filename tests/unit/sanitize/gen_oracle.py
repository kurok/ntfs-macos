"""Generate tests/unit/sanitize/oracle_data.h: general categories for the test oracle.

Usage (Environment A, Unicode 15.1.0):
  python3 -I tests/unit/sanitize/gen_oracle.py > tests/unit/sanitize/oracle_data.h

The oracle (oracle.h) states the ADR-016 label rules in terms of general categories and keeps
its own lists of the other properties. The production table (src/common/gen_label_cp.py) is
made by different code in a different form (denied ranges), so the exhaustive comparison over
all code points checks one against the other. This file is the category run table: from
U+0080 to U+10FFFF, each run of equal category as {first code point, two letters}.
"""
import sys
import unicodedata

if unicodedata.unidata_version != "15.1.0":
    sys.exit("gen_oracle.py: Unicode 15.1.0 needed, this Python has %s" % unicodedata.unidata_version)

runs = []
for cp in range(0x80, 0x110000):
    cat = "Cs" if 0xD800 <= cp <= 0xDFFF else unicodedata.category(chr(cp))
    if not runs or runs[-1][1] != cat:
        runs.append((cp, cat))

print("/* SPDX-License-Identifier: GPL-2.0-or-later */")
print("/* Generated by tests/unit/sanitize/gen_oracle.py from Unicode 15.1.0. Do not edit. */")
print("#ifndef NTFSMAC_SANITIZE_ORACLE_DATA_H")
print("#define NTFSMAC_SANITIZE_ORACLE_DATA_H")
print()
print("#include <stdint.h>")
print()
print("/* From U+0080: first code point of each run and its general category (two letters). */")
print("static const struct { uint32_t first; char cat[3]; } oracle_gc[] = {")
row = []
for cp, cat in runs:
    row.append('{ 0x%04X, "%s" },' % (cp, cat))
    if len(row) == 4:
        print("\t" + " ".join(row))
        row = []
if row:
    print("\t" + " ".join(row))
print("};")
print()
print("#endif /* NTFSMAC_SANITIZE_ORACLE_DATA_H */")
