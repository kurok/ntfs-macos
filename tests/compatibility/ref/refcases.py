"""C-REF-OP-01..12 (T-M3-15, criterion 3.10): twelve operation scripts run through NTFS-3G on Linux
(Environment A) and through the product's option set on macOS (Environment B); both images are dumped
on Linux and compared. Every difference must be listed in tests/compatibility/expected-differences.md
(the judge in reflib.py knows the rule ids) or the case fails.

Host cases, like C-REF-01 (cross_read.py): each drives the Environment B guest through the tart guest
agent and the Environment A container through vm/linux/run.sh. Per case (one fresh image per side):

  phase A (container)   reflib.py phase-a: mkntfs, mount, replay ops-NN.json, unmount, dump
  phase B (guest)       reflib.py phase-b: mkntfs, mount with the string src/options/options.c builds
                        (compiled from the repo into the guest), replay the same script, unmount
  host                  image out of the guest into build/ (git-ignored), into a container, always deleted
  dump (container)      reflib.py dump of the macOS-written image
  host                  reflib.judge

The scripts are tests/compatibility/ref/ops-NN.json (generated by make_ops.py).

Run (clones the VM, builds NTFS-3G in it with the full patch series, always deletes the VM):
    tests/harness/run-env-b.sh --orchestrate --cases 'C-REF-*'
Without NTFSMAC_B_VM (set by run-env-b.sh) the cases skip with a note.
"""

import json
import os
import shlex
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
COMPAT = os.path.dirname(HERE)
TESTS = os.path.dirname(COMPAT)
REPO = os.path.dirname(TESTS)
for p in (TESTS, HERE):
    if p not in sys.path:
        sys.path.insert(0, p)

import reflib  # noqa: E402
from harness import transport  # noqa: E402
from harness.core import Fail, case  # noqa: E402

SHIP = ("harness", "compatibility", "tools", "integration/functional", "integration/xattr")
GUEST_PATH = 'PATH="$HOME/ntfsmac/deps/bin:$HOME/ntfsmac/deps/sbin:$PATH"'
EXIT_SKIP = 3


def _jdump(path, obj):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=1, sort_keys=True)


def _log_remote(ctx, label, r):
    ctx.log("%s -> rc=%d" % (label, r.rc))
    err = r.err.decode("utf-8", "replace").strip()
    if err:
        ctx.log("%s stderr:\n%s" % (label, err[-4000:]))


def run_ref(ctx, n):
    spec = reflib.load_ops(n)
    vm_name = os.environ.get("NTFSMAC_B_VM")
    if not vm_name:
        ctx.skip("NTFSMAC_B_VM is not set: this case drives a running Environment B guest with NTFS-3G built "
                 "in it; run tests/harness/run-env-b.sh --orchestrate --cases 'C-REF-*'")
    vm = transport.VmTransport(vm_name, os.path.join(REPO, "vm", "macos", "tart.sh"))
    linux = transport.ContainerTransport(os.path.join(REPO, "vm", "linux", "run.sh"))

    d = vm.run("mktemp -d /tmp/ntfsmac-ref.XXXXXX")
    if d.rc != 0:
        raise RuntimeError("cannot reach the guest: %s" % d.err.decode("utf-8", "replace"))
    gdir = d.out.decode().strip()
    ctx.add_cleanup(lambda: vm.run("rm -rf %s" % shlex.quote(gdir)))
    vm.put_tree(TESTS, SHIP, gdir)
    vm.put_tree(REPO, ("include", "src/options"), gdir + "/repo")

    build_root = os.path.join(REPO, "build", "ref")
    os.makedirs(build_root, exist_ok=True)
    hdir = tempfile.mkdtemp(prefix="run-", dir=build_root)
    ctx.add_cleanup(lambda: shutil.rmtree(hdir, ignore_errors=True))
    host_img = os.path.join(hdir, "vol.img")
    tag = "refop%02d" % n

    # Phase A in the container (the image stays in the container, which is removed after the run).
    r = linux.run("PYTHONDONTWRITEBYTECODE=1 python3 /work/tests/compatibility/ref/reflib.py phase-a --op %d "
                  "--dir /tmp/%s --repo /work" % (n, tag), timeout=3600)
    _log_remote(ctx, "phase A (container)", r)
    if r.rc != 0:
        raise RuntimeError("phase A failed in the container (rc=%d)" % r.rc)
    a = json.loads(r.out.decode("utf-8"))

    # Phase B in the guest.
    py = "$(if [ -x /usr/bin/python3 ]; then echo /usr/bin/python3; else echo python3; fi)"
    cmd = "PYTHONDONTWRITEBYTECODE=1 %s %s %s/compatibility/ref/reflib.py phase-b --op %d --dir %s/out --repo %s/repo" % (
        GUEST_PATH, py, gdir, n, gdir, gdir)
    r = vm.run(cmd, timeout=3600)
    _log_remote(ctx, "phase B (guest)", r)
    if r.rc == EXIT_SKIP:
        ctx.skip("phase B skipped in the guest: %s" % r.err.decode("utf-8", "replace").strip().splitlines()[-1])
    if r.rc != 0:
        raise RuntimeError("phase B failed in the guest (rc=%d)" % r.rc)
    b = json.loads(r.out.decode("utf-8"))
    ctx.meta.update({"guest_os": b["os"], "macfuse_version": b["macfuse_version"], "ntfs3g_version": b["ntfs3g_version"]})

    # Image out of the guest, into a container for the Linux dump.
    r = vm.run_to_file("cat %s/out/vol.img" % gdir, host_img, timeout=3600)
    _log_remote(ctx, "copy image out", r)
    if r.rc != 0:
        raise RuntimeError("copying the image out of the guest failed (rc=%d)" % r.rc)
    if os.path.getsize(host_img) != b["image_size"] or reflib.sha256_path(host_img) != b["image_sha256"]:
        raise Fail("image changed in transit guest -> host")
    r = linux.run_from_file("mkdir -p /tmp/%s && cat > /tmp/%s/vol.img && PYTHONDONTWRITEBYTECODE=1 python3 "
                            "/work/tests/compatibility/ref/reflib.py dump --op %d --dir /tmp/%s --repo /work" % (
                                tag, tag, n, tag), host_img, timeout=3600)
    _log_remote(ctx, "dump of the macOS image (container)", r)
    if r.rc != 0:
        raise RuntimeError("dump failed in the container (rc=%d)" % r.rc)
    bd = json.loads(r.out.decode("utf-8"))
    os.remove(host_img)  # no image survives the run
    if bd["image_sha256_in"] != b["image_sha256"]:
        raise Fail("image changed in transit host -> container")
    b.update(bd)

    # Evidence (small text; no images).
    _jdump(ctx.evidence_file("phase-a.json"), a)
    _jdump(ctx.evidence_file("phase-b.json"), b)
    for side, doc in (("a", a), ("b", b)):
        with open(ctx.evidence_file("treedump-%s.txt" % side), "w", encoding="utf-8", errors="surrogateescape") as f:
            f.write(doc["treedump"])
    ctx.log("script %s (%s): %d operations; image %d MiB" % (spec["id"], spec["name"], len(spec["ops"]), spec["image_mib"]))
    ctx.log("A mount options: %s" % a["optstr"])
    ctx.log("B mount options: %s" % b["optstr"])
    ctx.log("Linux: NTFS-3G %s on %s; macOS: %s, macFUSE %s, NTFS-3G %s" % (
        a["ntfs3g_version"], a["os"], b["os"], b["macfuse_version"], b["ntfs3g_version"]))
    bad, explained, notes = reflib.judge(spec, a, b)
    with open(ctx.evidence_file("differences.txt"), "w", encoding="utf-8") as f:
        for rule, text in explained:
            f.write("EXPECTED %s %s\n" % (rule, text))
        for t in bad:
            f.write("UNEXPECTED %s\n" % t)
    for rule in sorted(set(r_ for r_, _t in explained)):
        ctx.log("expected difference %s: %d occurrence(s)" % (rule, len([1 for r_, _t in explained if r_ == rule])))
    for t in notes:
        ctx.log(t)
    if bad:
        for t in bad[:40]:
            ctx.log("MISMATCH " + t)
        raise Fail("%d differences not listed in expected-differences.md, first: %s" % (len(bad), bad[0]))
    ctx.log("PASS: the images of A and B give the same tree dump apart from %d listed difference(s)" % len(explained))


